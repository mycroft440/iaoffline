/** A curated GGUF that can be downloaded directly by the app. */
data class CatalogModel(
    val id: String,
    val displayName: String,
    val provider: ModelProvider,
    val repository: String,
    val fileName: String,
    val quantization: String,
    val approximateSizeBytes: Long,
    val sha256: String,
    /** Suggested *phone capacity*, not measured resident RAM; includes space for Android. */
    val recommendedRamBytes: Long,
    val totalParametersBillions: Double,
    val activeParametersBillions: Double? = null,
    val description: String,
    /** How the model compares with the others of its size class, shown in the details dialog. */
    val strengths: String? = null,
    /**
     * Presence penalty the model card recommends. GGUF has no key for it, unlike temperature and
     * top-k/top-p, which the runtime reads from the file itself.
     */
    val presencePenalty: Float = 0f,
) {
    val downloadUrl: String
        get() = "https://huggingface.co/$repository/resolve/main/$fileName?download=true"

    val apiIdPrefix: String
        get() = "local-catalog-$id-"

    /** MoE: active parameters describe compute per token, not the RAM occupied by the GGUF. */
    val isMoe: Boolean
        get() = activeParametersBillions != null

    /**
     * Large mixture-of-experts models: too big for a phone's RAM, but each word only uses a few
     * billion parameters, so they can run slowly by reading weights from storage.
     */
    val isExperimental: Boolean
        get() = isMoe && totalParametersBillions >= EXPERIMENTAL_MIN_TOTAL_BILLIONS

    companion object {
        const val EXPERIMENTAL_MIN_TOTAL_BILLIONS = 15.0
    }
}

